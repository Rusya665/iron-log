def get_exercise_standard(exercise_id: str, target_date_str: str, bodymass_log: dict, level: str = "Intermediate") -> int:
    if not bodymass_log:
        return 0
        
    dates = sorted(bodymass_log.keys())
    if not dates:
        return 0
        
    applicable_date = dates[0]
    for d in dates:
        if d <= target_date_str:
            applicable_date = d
        else:
            break
            
    bm_data = bodymass_log[applicable_date]
    current_bm = bm_data if isinstance(bm_data, (int, float)) else bm_data.get("mass", 0)
    
    if not current_bm:
        return 0
        
    rounded_bm = int(round(current_bm / 5.0) * 5.0)
    rounded_bm = max(50, min(rounded_bm, 140))
    
    ex_id_lower = exercise_id.lower()
    if "bench press" in ex_id_lower:
        table = BENCH_PRESS_STANDARDS_KG
    elif "squat" in ex_id_lower:
        table = SQUAT_STANDARDS_KG
    elif "deadlift" in ex_id_lower:
        table = DEADLIFT_STANDARDS_KG
    elif "overhead press" in ex_id_lower:
        table = OVERHEAD_PRESS_STANDARDS_KG
    elif "bicep curls" in ex_id_lower:
        table = BICEP_CURLS_STANDARDS_KG
    elif "pull-ups" in ex_id_lower or "pullups" in ex_id_lower:
        table = PULL_UPS_STANDARDS_KG
    else:
        return 0
        
    if rounded_bm not in table:
        return 0
        
    return table[rounded_bm].get(level, 0)
